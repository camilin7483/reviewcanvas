test('compone un mockup y exporta PNG verificable, SVG y JSON editable', async ({ page }) => {
  await openEditor(page)
  await link(page)
  await page.getByRole('button', { name: 'Vista previa', exact: true }).click()
  await expect(page.getByAltText('Tu diseño aplicado al mockup')).toHaveAttribute('style', /matrix3d/)
  await page.getByLabel('Elegir ambientación').selectOption('hotel')
  await expect(page.getByAltText('Recepción de hotel')).toBeVisible()
  await page.getByRole('button', { name: 'Cerrar', exact: true }).click()
  await page.getByRole('button', { name: 'Exportar' }).click()
  const dialog = page.getByRole('dialog')
  async function bytes() {
    const pending = page.waitForEvent('download')
    await dialog.getByRole('button', { name: 'Descargar', exact: true }).click()
    const file = await pending
    const stream = await file.createReadStream()
    const chunks: Buffer[] = []
    for await (const chunk of stream!) chunks.push(Buffer.from(chunk))
    return Buffer.concat(chunks)
  }
  const png = await bytes()
  expect(png.subarray(0, 8).toString('hex')).toBe('89504e470d0a1a0a')
  expect(png.readUInt32BE(16)).toBe(2000)
  expect(png.readUInt32BE(20)).toBe(2813)
  expect(png.readUInt32BE(41)).toBe(11811)
  const decoded = await page.evaluate(async (data) => {
    const scanner = await import('/src/editor/qr.ts' as string)
    const image = new Image()
    image.src = `data:image/png;base64,${data}`
    await image.decode()
    const crop = document.createElement('canvas')
    crop.width = crop.height = 950
    crop.getContext('2d')!.drawImage(image, 520, 1275, 950, 950, 0, 0, 950, 950)
    return scanner.readQr(crop)
  }, png.toString('base64'))
  expect(decoded).toBe(target)
  await dialog.getByRole('combobox', { name: 'Tipo de archivo', exact: true }).selectOption('SVG')
  const svg = (await bytes()).toString()
  expect(svg).toContain('<svg')
  expect(svg).toContain('<path')
  expect(svg).not.toContain('parsererror')
  expect(svg).not.toContain('data:image/svg+xml')
  await dialog.getByRole('combobox', { name: 'Tipo de archivo', exact: true }).selectOption('PDF')
  expect((await bytes()).subarray(0, 5).toString()).toBe('%PDF-')
  await dialog.getByRole('combobox', { name: 'Tipo de archivo', exact: true }).selectOption('JPG')
  expect((await bytes()).subarray(0, 3).toString('hex')).toBe('ffd8ff')
  await dialog.getByRole('combobox', { name: 'Tipo de archivo', exact: true }).selectOption('JSON')
  const project = JSON.parse((await bytes()).toString())
  expect(project.business).toBe('Casa Lumbre')
  expect(project.layers.some((layer: { kind: string }) => layer.kind === 'qr')).toBe(true)
  expect(project.url).toBe(target)
  await dialog.getByRole('button', { name: 'Cerrar', exact: true }).last().click()
  await page.goto('/proyectos')
  await expect(page.getByText('Casa Lumbre', { exact: true })).toBeVisible()
})

