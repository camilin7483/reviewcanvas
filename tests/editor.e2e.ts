const target = 'https://g.page/r/ReviewCanvasDemo/review'

async function openEditor(page: Page, path = '/editor') {
  await page.goto(path)
  await expect(page.locator('.stage canvas.upper-canvas')).toBeVisible()
  await expect(page.locator('.stage-loading')).toHaveCount(0, { timeout: 15_000 })
}
async function link(page: Page) {
  await page.getByRole('button', { name: 'Vincular negocio', exact: true }).click()
  await page.getByRole('button', { name: 'Escribir una reseña', exact: true }).click()
  await page.getByRole('textbox', { name: /Nombre del negocio/ }).fill('Casa Lumbre')
  await page.getByLabel('Enlace de reseñas o Place ID').fill(target)
  await page.getByRole('button', { name: 'Vincular y generar' }).click()
  await expect(page.getByRole('button', { name: 'QR verificado', exact: true })).toBeVisible({ timeout: 15_000 })
}

